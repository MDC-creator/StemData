#!/usr/bin/env bash
# StemCDataHub — one-command setup for a LOCAL test installation.
#
#   ./scripts/setup.sh                   random strong passwords (use this for anything shared)
#   ./scripts/setup.sh --simple-logins   root / root everywhere, for easy local testing
#   (Windows: run it in "Git Bash", which comes with Git for Windows)
#
# What it does (each step is skipped when it was already done, so it is safe to run again):
#   1. creates the .env files with random passwords and keys (never committed to Git)
#   2. starts the local copies of OMERO, Nextcloud and eLabFTW   (infra/dev-stack)
#   3. sets up eLabFTW once (database, team INDUZELL, an API key for our app)
#   4. builds and starts our app (web UI, API, worker)
#   5. loads demo content once (sample images from data/sample, if present)
# Needs: Docker Desktop (>= 8 GB memory for Docker), about 15 GB free disk, internet for the first run.

set -euo pipefail
export MSYS_NO_PATHCONV=1 MSYS2_ARG_CONV_EXCL="*"  # Git Bash on Windows: don't rewrite /paths in arguments

cd "$(dirname "$0")/.."
ROOT_DIR=$(pwd)
STATE=.setup
DEV="docker compose -f infra/dev-stack/compose.yaml"
APP="docker compose"
mkdir -p "$STATE"

SIMPLE=0
for arg in "$@"; do
  case $arg in
    --simple-logins) SIMPLE=1 ;;
    -h|--help) sed -n '2,14p' "$0"; exit 0 ;;
    *) echo "unknown option: $arg (see --help)" >&2; exit 1 ;;
  esac
done

say()  { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }
fail() { printf '\n\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }
rand() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c "${1:-24}"; }
# a login password: "root" in --simple-logins mode, otherwise random
pw()   { if (( SIMPLE )); then echo root; else rand "${1:-24}"; fi; }

# waits until a command succeeds; $1 = what, $2 = seconds, rest = command
wait_for() {
  local what=$1 limit=$2; shift 2
  local start=$SECONDS
  printf '    waiting for %s ' "$what"
  until "$@" >/dev/null 2>&1; do
    (( SECONDS - start > limit )) && { echo; fail "$what did not become ready within ${limit}s (see: docker compose logs)"; }
    printf '.'; sleep 3
  done
  echo " ready"
}

# ------------------------------------------------------------------------------------------------ 0
say "Checking Docker"
docker info >/dev/null 2>&1 || fail "Docker is not running. Start Docker Desktop and run this script again."
docker compose version >/dev/null 2>&1 || fail "'docker compose' (v2) is missing. Update Docker Desktop."
mem=$(docker info --format '{{.MemTotal}}' 2>/dev/null || echo 0)
if (( mem > 0 && mem < 7500000000 )); then
  echo "    Warning: Docker has only $((mem / 1000000000)) GB memory; 8 GB is recommended (Docker Desktop > Settings > Resources)."
fi

# ------------------------------------------------------------------------------------------------ 1
say "Creating configuration (.env files)"
if [[ ! -f infra/dev-stack/.env ]]; then
  echo "    getting an eLabFTW secret key (pulls the eLabFTW image the first time)"
  elab_key=$(docker run --rm --entrypoint sh elabftw/elabimg:6.0.8 \
    -c "php -d memory_limit=10M -d open_basedir='' bin/init tools:genkey" | tr -d '\r\n')
  [[ $elab_key == def* ]] || fail "could not generate the eLabFTW secret key"
  cat > infra/dev-stack/.env <<EOF
# generated by scripts/setup.sh — local test installation only, never commit this file
OMERO_DB_PASSWORD=$(rand)
OMERO_ROOT_PASSWORD=$(pw)
NEXTCLOUD_ADMIN_USER=$( (( SIMPLE )) && echo root || echo admin )
NEXTCLOUD_ADMIN_PASSWORD=$(pw)
ELAB_DB_ROOT_PASSWORD=$(rand)
ELAB_DB_PASSWORD=$(rand)
ELAB_SECRET_KEY=$elab_key
ELAB_DEV_PASSWORD=$(rand 16)
ELAB_LAB_PASSWORD=$(rand 16)
ELAB_API_KEY=local-$(rand 40)
ELAB_LOGIN_EMAIL=$( (( SIMPLE )) && echo root@root.local || echo dev@stemchub.local )
SIMPLE_LOGINS=$SIMPLE
EOF
  echo "    wrote infra/dev-stack/.env"
else
  echo "    infra/dev-stack/.env exists, keeping it"
fi
# shellcheck disable=SC1091
set -a; source infra/dev-stack/.env; set +a

if [[ ! -f .env ]]; then
  sed -e "s|^APP_DB_PASSWORD=.*|APP_DB_PASSWORD=$(rand)|" \
      -e "s|^ADMIN_USERNAME=.*|ADMIN_USERNAME=$( (( SIMPLE )) && echo root || echo admin )|" \
      -e "s|^ADMIN_PASSWORD=.*|ADMIN_PASSWORD=$(pw 16)|" \
      -e "s|^ALLOW_SIMPLE_PASSWORDS=.*|ALLOW_SIMPLE_PASSWORDS=$( (( SIMPLE )) && echo true || echo false )|" \
      -e "s|^NEXTCLOUD_USER=.*|NEXTCLOUD_USER=$NEXTCLOUD_ADMIN_USER|" \
      -e "s|^WEBHOOK_TOKEN=.*|WEBHOOK_TOKEN=$(rand 32)|" \
      -e "s|^OMERO_PASSWORD=.*|OMERO_PASSWORD=$OMERO_ROOT_PASSWORD|" \
      -e "s|^NEXTCLOUD_PASSWORD=.*|NEXTCLOUD_PASSWORD=$NEXTCLOUD_ADMIN_PASSWORD|" \
      -e "s|^ELAB_API_KEY=.*|ELAB_API_KEY=$ELAB_API_KEY|" \
      .env.example > .env
  echo "    wrote .env"
else
  echo "    .env exists, keeping it"
fi
ADMIN_USERNAME=$(grep '^ADMIN_USERNAME=' .env | cut -d= -f2-)
ADMIN_PASSWORD=$(grep '^ADMIN_PASSWORD=' .env | cut -d= -f2-)

# ------------------------------------------------------------------------------------------------ 2
say "Starting OMERO, Nextcloud and eLabFTW (first time: several GB of downloads)"
$DEV up -d

# ------------------------------------------------------------------------------------------------ 3
if [[ ! -f $STATE/elabftw-ready ]]; then
  say "Setting up eLabFTW (team INDUZELL, API key for our app)"
  wait_for "eLabFTW" 300 sh -c "$DEV exec -T elabftw php bin/init list"
  sed -e "s|__ELAB_DEV_PASSWORD__|$ELAB_DEV_PASSWORD|" \
      -e "s|__ELAB_LAB_PASSWORD__|$ELAB_LAB_PASSWORD|" \
      -e "s|__ELAB_API_KEY__|$ELAB_API_KEY|" \
      infra/dev-stack/elabftw-populate.yml > infra/dev-stack/elabftw-populate.local.yml
  # db:populate creates the database structure itself, then the team and users; its SQL output goes to a log
  log="$STATE/elabftw-setup.log"
  $DEV exec -T elabftw sh -c 'cat > /run/elabftw/populate.yml && php bin/init db:populate -y /run/elabftw/populate.yml; rc=$?; rm -f /run/elabftw/populate.yml; exit $rc' \
    < infra/dev-stack/elabftw-populate.local.yml > "$log" 2>&1 \
    || { tail -20 "$log"; fail "eLabFTW setup failed (full log: $log)"; }
  grep -E '(team|user):' "$log" | sed 's/^[^+]*+/    created/' || true
  if [[ ${SIMPLE_LOGINS:-0} == 1 ]]; then
    # eLabFTW logs in with an email address, so "root" becomes root@root.local; allow the short password
    hash=$($DEV exec -T elabftw php -r 'echo password_hash("root", PASSWORD_DEFAULT);')
    $DEV exec -T -e H="$hash" elabftw-db sh -c 'mysql -uelabftw -p"$MYSQL_PASSWORD" elabftw -e "UPDATE users SET email=\"root@root.local\", password_hash=\"$H\" WHERE email=\"dev@stemchub.local\"; UPDATE config SET conf_value=\"4\" WHERE conf_name=\"min_password_length\";"' 2>/dev/null \
      || fail "could not set the eLabFTW login to root@root.local"
    echo "    eLabFTW login set to root@root.local / root"
  fi
  touch "$STATE/elabftw-ready"
else
  echo "    eLabFTW already set up"
fi

wait_for "OMERO (first start takes a few minutes)" 600 \
  sh -c "$DEV exec -T omero-server /opt/omero/server/venv3/bin/omero login -s localhost -u root -w \"\$0\" -q" "$OMERO_ROOT_PASSWORD"
wait_for "Nextcloud" 300 sh -c "$DEV exec -T nextcloud php -r 'echo file_get_contents(\"http://localhost/status.php\");' | grep -q '\"installed\":true'"

# ------------------------------------------------------------------------------------------------ 4
say "Building and starting StemCDataHub (first time: about 10 minutes)"
$APP up -d --build
wait_for "the StemCDataHub API" 300 sh -c "$APP exec -T api python -c \"import urllib.request; urllib.request.urlopen('http://localhost:8000/api/openapi.json')\""

# ------------------------------------------------------------------------------------------------ 5
if [[ ! -f $STATE/seeded ]]; then
  say "Loading demo content"
  if ! ls data/sample/*.czi >/dev/null 2>&1; then
    echo "    no sample images in data/sample/ — loading demo runs and process data only"
    echo "    (later: copy the .czi files into data/sample/ or use the Upload page)"
  fi
  $APP exec -T api python -m stemchub.seed
  touch "$STATE/seeded"
fi

# ------------------------------------------------------------------------------------------------ done
cat <<EOF

$(printf '\033[1;32m')StemCDataHub is running.$(printf '\033[0m')  The worker imports and analyses the demo images within a few minutes.

  StemCDataHub   http://localhost:8090        user: $ADMIN_USERNAME   password: $ADMIN_PASSWORD
  OMERO.web      http://localhost:4080        user: root    password: $OMERO_ROOT_PASSWORD
  Nextcloud      http://localhost:8081        user: $NEXTCLOUD_ADMIN_USER   password: $NEXTCLOUD_ADMIN_PASSWORD
  eLabFTW        https://localhost:8443       user: ${ELAB_LOGIN_EMAIL:-dev@stemchub.local}   password: $( [[ ${SIMPLE_LOGINS:-0} == 1 ]] && echo root || echo "$ELAB_DEV_PASSWORD" )
                 (self-signed certificate: accept the browser warning)

  All passwords are in .env and infra/dev-stack/.env (git-ignored).
  Stop:   docker compose stop && docker compose -f infra/dev-stack/compose.yaml stop
  Start:  ./scripts/setup.sh   (or the two "up -d" commands)
EOF
